FIRST, LAST = 32, 90


def byte(row: str) -> int:
    assert len(row) == 8, row
    return int("".join("1" if c == "#" else "0" for c in row), 2)


def tile_lines(name: str, rows: list[str]) -> list[str]:
    assert len(rows) == 16, name
    out = [f"{name}:"]
    for row in rows:
        assert len(row) == 16, (name, row)
        out.append(f"        .BYTE   {byte(row[:8]):03o},{byte(row[8:]):03o}      ; {row}")
    return out


def glyph_lines(ch: str, rows: list[str]) -> list[str]:
    assert len(rows) == 8, ch
    label = f"; '{ch}'" if ch != " " else "; space"
    out = [label]
    for row in rows:
        out.append(f"        .BYTE   {byte(row):03o}          ; {row}")
    return out


def main() -> None:
    lines = [
        "        .TITLE  ART",
        "        .SBTTL  CellWar - the tiles and the font",
        "; ART.MAC - drawn by source/gen_art.py; edit the pictures there.",
        "        .GLOBL  TFOG,TEMPTY,TINF,TFRT1,TFRT2,TFAC,FONT",
        "",
        "; --- the tiles: 16 x 16, two bytes a row, bit 7 leftmost ------------",
    ]
    for name, rows in TILES.items():
        lines += tile_lines(name, rows)
    lines += ["", "; --- the font: ' '..'Z', 8 bytes a glyph ---------------------------", "FONT:"]
    for code in range(FIRST, LAST + 1):
        ch = chr(code)
        lines += glyph_lines(ch, GLYPHS.get(ch, GLYPHS[" "]))
    lines += ["        .END", ""]
    OUT.write_text("\n".join(lines), encoding="ascii", newline="\r\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
