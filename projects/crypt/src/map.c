int map_at(int x, int y)
{
	if (x < 0 || y < 0 || x >= MAP_SIDE || y >= MAP_SIDE)
		return 1;
	return map[(y << 5) + x];
}

int map_free(int x, int y)
{
	return map_at(x >> 8, y >> 8) == 0;
}

void map_test(void)
{
	int x, y;

	for (y = 0; y < MAP_SIDE; y++)
		for (x = 0; x < MAP_SIDE; x++) {
			char c = level[y][x];
			map[(y << 5) + x] = (unsigned char)(c == '#');
			if (c == 'S') {
				map_startX = x;
				map_startY = y;
			}
		}
}
